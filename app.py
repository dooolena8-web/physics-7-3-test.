import streamlit as st
import requests

# НАЛАШТУВАННЯ: Вставте сюди ваше посилання на Google Apps Script Web App
WEB_APP_URL = "https://script.google.com/macros/s/AKfycbyXJYIWDayonOMxuMlECdPmDfbET_ljan1PyhoxuUN1w_Iv5Zi9ZtRhjqgPATpJKrxv/exec"

st.set_page_config(page_title="Тест: Фізичні величини", layout="centered")

st.title("📏 Тест: Фізичні величини та їх вимірювання")
st.subheader("7 клас. Нова українська школа")

# Блок реєстрації учня
st.markdown("### 📝 Реєстрація учасника")
col1, col2, col3 = st.columns(3)
with col1:
    last_name = st.text_input("Прізвище").strip()
with col2:
    first_name = st.text_input("Ім'я").strip()
with col3:
    student_class = st.text_input("Клас (наприклад, 7-Б)").strip()

st.divider()

score = 0
answers = {}

# --- 1. Одна відповідь ---
st.markdown("#### 1. Оберіть, що з переліченого є ФІЗИЧНОЮ ВЕЛИЧИНОЮ:")
q1 = st.radio("Варіанти:", ["Книга", "Час", "Годинник", "Кипіння"], index=None, key="q1")
with st.expander("💡 Підказка"):
    st.info("Фізична величина — це те, що ми можемо виміряти приладами й виразити числом (наприклад, порахувати хвилини чи секунди).")
if q1 == "Час": score += 1
answers["q1"] = q1

# --- 2. Одна відповідь ---
st.markdown("#### 2. Оберіть, що з переліченого є ФІЗИЧНИМ ТІЛОМ:")
q2 = st.radio("Варіанти:", ["Метр", "Довжина", "Лінійка", "Вимірювання"], index=None, key="q2")
with st.expander("💡 Підказка"):
    st.info("Фізичне тіло — це будь-який предмет, який має форму, об'єм і межі. Його можна взяти в руки.")
if q2 == "Лінійка": score += 1
answers["q2"] = q2

# --- 3. ДВІ правильні відповіді ---
st.markdown("#### 3. ⚠️ Оберіть ДВІ ПРАВИЛЬНІ відповіді: Які з цих приладів призначені для вимірювання ЛІНІЙНИХ РОЗМІРІВ (довжини, висоти, відстані)?")
q3_1 = st.checkbox("Рулетка", key="q3_1")
q3_2 = st.checkbox("Секундомір", key="q3_2")
q3_3 = st.checkbox("Штангенциркуль", key="q3_3")
q3_4 = st.checkbox("Термометр", key="q3_4")
with st.expander("💡 Підказка"):
    st.info("Подумайте, чим майстер вимірює довжину дошки, а учень — товщину маленької детальки.")
q3_res = []
if q3_1: q3_res.append("Рулетка")
if q3_2: q3_res.append("Секундомір")
if q3_3: q3_res.append("Штангенциркуль")
if q3_4: q3_res.append("Термометр")
if q3_1 and q3_3 and not q3_2 and not q3_4: score += 1
answers["q3"] = ", ".join(q3_res)

# --- 4. Відкрита форма ---
st.markdown("#### 4. ✍️ Запишіть відповідь з малої літери:\nЯка основна одиниця вимірювання часу в Міжнародній системі одиниць (СІ)?")
q4 = st.text_input("Ваша відповідь (одне слово):", key="q4").strip().lower()
with st.expander("💡 Підказка"):
    st.info("Не хвилини, не години. Слово починається на літеру 'с'.")
if q4 in ["секунда", "секунди"]: score += 1
answers["q4"] = q4

# --- 5. Одна відповідь ---
st.markdown("#### 5. Що означає «виміряти фізичну величину»?")
q5 = st.radio("Варіанти:", 
              ["Порівняти її з однорідною величиною, взятою за одиницю", "Подивитися на око", "Записати формулу в зошит", "Запитати у вчителя"], 
              index=None, key="q5")
with st.expander("💡 Підказка"):
    st.info("Коли ми міряємо довжину столу лінійкою, ми рахуємо, скільки разів еталонний 'один сантиметр' уміститься в цьому столі.")
if q5 == "Порівняти її з однорідною величиною, взятою за одиницю": score += 1
answers["q5"] = q5

# --- 6. Одна відповідь ---
st.markdown("#### 6. Значення якої величини ми дізнаємося за допомогою мензурки (вимірювального циліндра)?")
q6 = st.radio("Варіанти:", ["Маса рідини", "Об'єм рідини або тіла", "Температура води", "Площа дна"], index=None, key="q6")
with st.expander("💡 Підказка"):
    st.info("У мензурку наливають воду або кидають камінчик, щоб дізнатися, скільки простору (мілілітрів чи кубічних сантиметрів) вони займають.")
if q6 == "Об'єм рідини або тіла": score += 1
answers["q6"] = q6

# --- 7. ДВІ правильні відповіді ---
st.markdown("#### 7. ⚠️ Оберіть ДВІ ПРАВИЛЬНІ відповіді: Які з цих одиниць є ОДИНКАМИ ВИМІРЮВАННЯ ОБ'ЄМУ?")
q7_1 = st.checkbox("Кілограм", key="q7_1")
q7_2 = st.checkbox("Літр", key="q7_2")
q7_3 = st.checkbox("Метр кубічний ($м^3$)", key="q7_3")
q7_4 = st.checkbox("Міліметр", key="q7_4")
with st.expander("💡 Підказка"):
    st.info("Згадайте, в яких одиницях продають молоко або вимірюють кількість води в басейні.")
q7_res = []
if q7_1: q7_res.append("Кілограм")
if q7_2: q7_res.append("Літр")
if q7_3: q7_res.append("Метр кубічний")
if q7_4: q7_res.append("Міліметр")
if q7_2 and q7_3 and not q7_1 and not q7_4: score += 1
answers["q7"] = ", ".join(q7_res)

# --- 8. Відкрита форма ---
st.markdown("#### 8. ✍️ Запишіть відповідь з малої літери:\nЗначення найменшої поділки шкали вимірювального приладу називається ... поділки.")
q8 = st.text_input("Ваша відповідь (одне слово):", key="q8").strip().lower()
with st.expander("💡 Підказка"):
    st.info("Слово починається на літеру 'ц'. Щоб її знайти, треба відняти два сусідні числа на шкалі й поділити на кількість штрихів між ними.")
if q8 == "ціна": score += 1
answers["q8"] = q8

# --- 9. Одна відповідь ---
st.markdown("#### 9. На лінійці сусідні числа 10 см і 11 см. Між ними є 10 маленьких проміжків (поділок). Яка ціна поділки цієї лінійки?")
q9 = st.radio("Варіанти:", ["1 см", "0,1 см (або 1 мм)", "0,5 см", "10 мм"], index=None, key="q9")
with st.expander("💡 Підказка"):
    st.info("Розрахунок: $(11 - 10) / 10 = 1 / 10 = ...$")
if q9 == "0,1 см (або 1 мм)": score += 1
answers["q9"] = q9

# --- 10. Одна відповідь ---
st.markdown("#### 10. Будь-яке вимірювання приладом не є абсолютно точним. Різниця між виміряним значенням і справжнім значенням називається:")
q10 = st.radio("Варіанти:", ["Помилка учня", "Похибка вимірювання", "Ціна приладу", "Межа шкали"], index=None, key="q10")
with st.expander("💡 Підказка"):
    st.info("Це словосполучення починається на 'п'. Вона зазвичай дорівнює половині ціни поділки приладу.")
if q10 == "Похибка вимірювання": score += 1
answers["q10"] = q10

# --- 11. ДВІ правильні відповіді ---
st.markdown("#### 11. ⚠️ Оберіть ДВІ ПРАВИЛЬНІ відповіді: Які з цих чинників впливають на появу похибки під час лабораторної роботи?")
q11_1 = st.checkbox("Недосконалість конструкції самого приладу", key="q11_1")
q11_2 = st.checkbox("Колір корпусу приладу", key="q11_2")
q11_3 = st.checkbox("Неточний погляд дослідника на шкалу під кутом", key="q11_3")
q11_4 = st.checkbox("Погода на іншій планеті", key="q11_4")
with st.expander("💡 Підказка"):
    st.info("Подумайте, чому результати у різних учнів можуть трохи відрізнятися: через неідеальність лінійки чи неправильне положення ока?")
q11_res = []
if q11_1: q11_res.append("Недосконалість приладу")
if q11_2: q11_res.append("Колір корпусу")
if q11_3: q11_res.append("Неточний погляд")
if q11_4: q11_res.append("Погода")
if q11_1 and q11_3 and not q11_2 and not q11_4: score += 1
answers["q11"] = ", ".join(q11_res)

# --- 12. Відкрита форма ---
st.markdown("#### 12. ✍️ Запишіть відповідь з малої літери:\nЯк називається максимальне значення величини, яке можна виміряти за допомогою конкретної шкали приладу? Верхня ... вимірювання.")
q12 = st.text_input("Ваша відповідь (одне слово):", key="q12").strip().lower()
with st.expander("💡 Підказка"):
    st.info("Слово починається на літеру 'м'. Це крайня лінія або фінал можливостей шкали.")
if q12 == "межа": score += 1
answers["q12"] = q12

st.divider()

# Кнопка завершення
if st.button("🏁 Завершити тест та відправити результати", type="primary"):
    if not last_name or not first_name or not student_class:
        st.error("❌ Заповніть обов'язково: Прізвище, Ім'я та Клас!")
    else:
        data = {
            "prizvysche": last_name, "imya": first_name, "klas": student_class, "ocinka": score,
            "q1": answers.get("q1", ""), "q2": answers.get("q2", ""), "q3": answers.get("q3", ""),
            "q4": answers.get("q4", ""), "q5": answers.get("q5", ""), "q6": answers.get("q6", ""),
            "q7": answers.get("q7", ""), "q8": answers.get("q8", ""), "q9": answers.get("q9", ""),
            "q10": answers.get("q10", ""), "q11": answers.get("q11", ""), "q12": answers.get("q12", "")
        }
        try:
            requests.post(WEB_APP_URL, data=data)
            st.success(f"🎉 Чудово, {first_name}! Результати успішно занесено в таблицю.")
            st.metric(label="Твій бал:", value=f"{score} з 12")
            if score >= 10:
                st.balloons()
        except:
            st.error("Помилка відправки. Перевірте інтернет.")
